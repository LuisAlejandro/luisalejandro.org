#!/usr/bin/env node
/**
 * Wholmaster license operations.
 *
 *   node scripts/wholmaster-license.mjs keygen
 *   node scripts/wholmaster-license.mjs mint --slug acme-gym --to "Acme Gym" --seats 2 --tier gym --major 1
 *   node scripts/wholmaster-license.mjs sign-fixture --out <path>
 *
 * `keygen` prints a PKCS8 private key (base64, for WHOLMASTER_LICENSE_SIGNING_KEY) and the matching
 * SPKI public key (base64, for the desktop's embedded verifier). Back the private key up offline.
 *
 * This file duplicates the artifact encoding on purpose: it must not import Next-only modules, and
 * the desktop verifies these bytes in Go. The Go test in U4 keeps the two sides honest.
 */

import crypto from "crypto";
import fs from "fs";
import path from "path";

const KEY_PREFIX = "WMK1";
const CERT_PREFIX = "WMC1";

const b64url = (buf) =>
  buf
    .toString("base64")
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/, "");

function sign(prefix, payload, privateKey) {
  const body = `${prefix}.${b64url(Buffer.from(JSON.stringify(payload), "utf8"))}`;
  return `${body}.${b64url(crypto.sign(null, Buffer.from(body, "utf8"), privateKey))}`;
}

function arg(name, fallback = undefined) {
  const i = process.argv.indexOf(`--${name}`);
  if (i === -1) return fallback;
  return process.argv[i + 1] ?? fallback;
}

function keygen() {
  const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519");
  const priv = privateKey
    .export({ format: "der", type: "pkcs8" })
    .toString("base64");
  const pub = publicKey
    .export({ format: "der", type: "spki" })
    .toString("base64");
  console.error(
    "WARNING: this output contains the PRIVATE signing key. Do not save it inside a git repo.\n" +
      "Put privateKey in the issuer's environment (WHOLMASTER_LICENSE_SIGNING_KEY) and back it up\n" +
      "offline. Only publicKey is ever committed, and only via `emit-go`.\n"
  );
  console.log(
    JSON.stringify(
      { kid: "wm-2026", privateKey: priv, publicKey: pub },
      null,
      2
    )
  );
}

/**
 * emit-go prints the Go constants that embed the public key in the desktop verifier. This replaces
 * hand-pasting, which is where a base64 typo would silently disable every activation.
 */
function emitGo() {
  const publicKey = arg("public");
  const kid = arg("kid", process.env.WHOLMASTER_LICENSE_KID || "");
  if (!publicKey)
    throw new Error(
      "--public <base64 SPKI> is required (the publicKey from keygen)"
    );
  if (!kid) throw new Error("--kid is required");

  // Fail here rather than in the desktop: the value must be a real ed25519 SPKI public key.
  const parsed = crypto.createPublicKey({
    key: Buffer.from(publicKey, "base64"),
    format: "der",
    type: "spki",
  });
  if (parsed.asymmetricKeyType !== "ed25519") {
    throw new Error("that public key is not ed25519");
  }

  console.log(`// Code generated by scripts/wholmaster-license.mjs emit-go. DO NOT EDIT.
//
// The public key is not a secret; it ships with the binary because offline verification needs it.
// Regenerate this block instead of editing it by hand.

package license
const (
	embeddedKID = "${kid}"
	// embeddedPublicKeySPKI is base64 of the DER SubjectPublicKeyInfo.
	embeddedPublicKeySPKI = "${publicKey}"
)`);
}

async function mint() {
  const slug = arg("slug");
  if (!slug) throw new Error("--slug is required");
  const raw = process.env.WHOLMASTER_LICENSE_SIGNING_KEY;
  const kid = process.env.WHOLMASTER_LICENSE_KID;
  if (!raw || !kid)
    throw new Error(
      "WHOLMASTER_LICENSE_SIGNING_KEY and WHOLMASTER_LICENSE_KID are required"
    );

  const privateKey = crypto.createPrivateKey({
    key: Buffer.from(raw, "base64"),
    format: "der",
    type: "pkcs8",
  });
  const payload = {
    kid,
    lid: arg("lid", slug),
    tier: arg("tier", "gym"),
    seats: Number(arg("seats", "2")),
    mm: Number(arg("major", "1")),
    to: arg("to", ""),
  };
  console.log(sign(KEY_PREFIX, payload, privateKey));
}

function signFixture() {
  const out = arg("out");
  if (!out) throw new Error("--out is required");
  const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519");
  const kid = "test-2026";
  const fp = ["fixture-hash-a", "fixture-hash-b", "fixture-hash-c"];
  const key = sign(
    KEY_PREFIX,
    {
      kid,
      lid: "fixture-lid",
      tier: "gym",
      seats: 2,
      mm: 1,
      to: "Fixture Gym",
    },
    privateKey
  );
  const cert = sign(
    CERT_PREFIX,
    { kid, lid: "fixture-lid", fp, seat: 1, iat: 1762473600 },
    privateKey
  );

  const fixture = {
    note: "Generated by scripts/wholmaster-license.mjs sign-fixture. Signed with a throwaway key.",
    kid,
    publicKey: publicKey
      .export({ format: "der", type: "spki" })
      .toString("base64"),
    key,
    certificate: cert,
    fingerprint: fp,
    expect: { tier: "gym", seats: 2, licensedTo: "Fixture Gym", maxMajor: 1 },
  };
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, JSON.stringify(fixture, null, 2) + "\n");
  console.log(`wrote ${out}`);
}

const command = process.argv[2];
switch (command) {
  case "keygen":
    keygen();
    break;
  case "mint":
    await mint();
    break;
  case "sign-fixture":
    signFixture();
    break;
  case "emit-go":
    emitGo();
    break;
  default:
    console.error(
      "usage: wholmaster-license.mjs <keygen|emit-go|mint|sign-fixture> [options]"
    );
    process.exit(1);
}
